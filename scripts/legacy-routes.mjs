import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

// Project pages from the unpublished 2026-10-11 /work/:slug routes.
export const WORK_SLUGS = ["bakbak", "burnhop", "greytrace", "masala", "templio"];

// Paths with no single replacement page. Listed once; both slash forms stay 404.
export const UNMATCHED_ROUTES = [
  ["/resume", "Production résumé page was not rebuilt."],
  ["/experience/autodesk", "Employer chapter covered several projects and has no single replacement page."],
  ["/experience/siemens", "Employer chapter covered several projects and has no single replacement page."],
  ["/experience/accenture", "Employer chapter covered several projects and has no single replacement page."],
  ["/api/contact", "Contact Worker endpoint is not configured."],
  ["/about", "Unpublished about page was not rebuilt. Low HP Studio is a project record, not that page."],
  ["/playground", "Unpublished playground index included excluded Receipt creator and TypeRush entries."],
  ["/work", "Unpublished selected-work index is a different collection from /projects/."],
];

export function readArchivedRoutes(contentDir) {
  return readdirSync(contentDir)
    .filter((name) => name.endsWith(".md"))
    .map((name) => {
      const text = readFileSync(join(contentDir, name), "utf8");
      const match = text.match(/^archivedRoute:\s*"([^"]+)"/m);
      return {
        slug: name.slice(0, -3),
        archivedRoute: match?.[1] ?? null,
      };
    });
}

export function buildRedirectRules(root) {
  const notes = readArchivedRoutes(join(root, "src/content/notes"));
  const projects = readArchivedRoutes(join(root, "src/content/projects"));
  const rules = [];

  const add = (source, destination) => {
    const bare = source.replace(/\/$/, "");
    rules.push({ source: bare, destination });
    rules.push({ source: `${bare}/`, destination });
  };

  add("/blogs", "/notes/");

  for (const note of notes.sort((left, right) => left.slug.localeCompare(right.slug))) {
    if (!note.archivedRoute) throw new Error(`Note ${note.slug} is missing archivedRoute`);
    if (note.archivedRoute !== `/blogs/${note.slug}`) {
      throw new Error(`Note ${note.slug} archivedRoute is ${note.archivedRoute}`);
    }
    add(note.archivedRoute, `/notes/${note.slug}/`);
  }

  const bakbak = projects.find((project) => project.slug === "bakbak");
  if (bakbak?.archivedRoute !== "/bakbak") throw new Error("Bakbak archivedRoute must be /bakbak");
  add("/bakbak", "/projects/bakbak/");

  for (const slug of [...WORK_SLUGS].sort()) {
    if (!projects.some((project) => project.slug === slug)) {
      throw new Error(`Missing project page for archived /work/${slug}`);
    }
    add(`/work/${slug}`, `/projects/${slug}/`);
  }

  return rules;
}

export function renderRedirects(rules) {
  const lines = [
    "# Permanent redirects for archived URLs that have a replacement page.",
    "# Generated by scripts/write-redirects.mjs.",
    "# Destinations use the canonical trailing slash so html_handling does not add a second hop.",
    "# https://developers.cloudflare.com/workers/static-assets/redirects/",
    "",
  ];
  for (const rule of rules) lines.push(`${rule.source} ${rule.destination} 301`);
  lines.push(
    "",
    "# Unmatched archived routes stay 404. They are not redirected to the homepage.",
    "# Both slash variants are unmatched. Cloudflare does not evaluate fragments, so /bakbak#download follows /bakbak.",
    "# The Bakbak project page has no download section.",
  );
  for (const [path, reason] of UNMATCHED_ROUTES) lines.push(`# ${path} — ${reason}`);
  lines.push("");
  return lines.join("\n");
}
